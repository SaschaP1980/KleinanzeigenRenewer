'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const InventoryLoadState = require('../src/app/inventory-loading-state.js');
const root = path.resolve(__dirname, '..');
const source = file => fs.readFileSync(path.join(root,file),'utf8');
const delay = () => { let resolve; const promise = new Promise(done => {resolve=done;}); return {promise,resolve}; };

(async () => {
  const changes=[];
  const state=InventoryLoadState.create({onChange:(view,snapshot)=>changes.push({view,...snapshot})});
  assert.equal(state.snapshot('inventory').phase,'loading');
  assert.equal(state.snapshot('trash').phase,'loading');
  const first=state.begin('profile-A');
  assert.equal(state.isCurrent(first),true);
  assert.equal(state.snapshot('inventory').lastVerifiedCount,null);
  assert.equal(state.snapshot('trash').lastVerifiedCount,null);
  const inv=delay(), trash=delay();
  const runInventory=inv.promise.then(records=>state.settle(first,'inventory',{records}));
  const runTrash=trash.promise.then(records=>state.settle(first,'trash',{records}));
  assert.equal(state.snapshot('inventory').phase,'loading','inventar stays loading throughout delayed read');
  assert.equal(state.snapshot('trash').phase,'loading','trash stays independently loading');
  inv.resolve(Array.from({length:61},(_,i)=>({inventoryId:'i-'+i})));
  assert.equal(await runInventory,true);
  assert.equal(state.snapshot('inventory').phase,'ready');
  assert.equal(state.snapshot('inventory').lastVerifiedCount,61);
  assert.equal(state.snapshot('trash').phase,'loading','inventory success must not imply trash success');
  trash.resolve(Array.from({length:90},(_,i)=>({inventoryId:'t-'+i})));
  assert.equal(await runTrash,true);
  assert.equal(state.snapshot('trash').lastVerifiedCount,90);
  const retry=state.begin('profile-A');
  assert.equal(state.snapshot('inventory').phase,'loading');
  assert.equal(state.snapshot('inventory').lastVerifiedCount,61,'preserve last verified same-profile count');
  assert.equal(state.snapshot('trash').lastVerifiedCount,90);
  assert.equal(state.settle(retry,'trash',{error:new Error('KR_UPDATE_FENCE_ATOMIC_BUSY')}),true);
  assert.equal(state.snapshot('trash').phase,'error');
  assert.equal(state.snapshot('trash').lastVerifiedCount,90,'failed read cannot imply empty');
  assert.equal(state.snapshot('inventory').phase,'loading');
  assert.equal(state.settle(retry,'inventory',{records:[]}),true);
  assert.equal(state.snapshot('inventory').phase,'ready','confirmed empty requires successful array');
  assert.equal(state.snapshot('inventory').lastVerifiedCount,0);
  const old=state.begin('profile-A');
  const newer=state.begin('profile-B');
  assert.equal(state.isCurrent(old),false);
  assert.equal(state.settle(old,'inventory',{records:[{inventoryId:'late-old'}]}),false);
  assert.equal(state.settle(old,'trash',{records:[{inventoryId:'late-old'}]}),false);
  assert.equal(state.snapshot('inventory').lastVerifiedCount,null,'different profile may not inherit counts');
  assert.equal(state.snapshot('trash').lastVerifiedCount,null);
  assert.equal(state.settle(newer,'trash',{records:[]}),true);
  assert.equal(state.snapshot('inventory').phase,'loading','trash may finish first');
  assert.equal(state.snapshot('trash').phase,'ready');
  assert.equal(changes.filter(c=>c.view==='inventory').length>0,true);

  const html=source('src/app/app.html');
  const app=source('src/app/app.js');
  const css=source('src/app/app.css');
  const pkg=source('scripts/package.py');
  assert.match(html,/id="inventoryList"[^>]*>[\s\S]*?Inventar wird geladen …/);
  assert.match(html,/id="trashList"[^>]*>[\s\S]*?Papierkorb wird geladen …/);
  assert.match(html,/id="inventoryHeaderCount">…<\/span>/);
  assert.match(html,/id="trashHeaderCount">…<\/span>/);
  assert.doesNotMatch(html,/id="inventoryCount">0 Einträge/);
  assert.doesNotMatch(html,/id="trashCount">0 Einträge/);
  assert.match(html,/src="inventory-loading-state\.js"/);
  assert.match(pkg,/src\/app\/inventory-loading-state\.js/);
  assert.match(app,/inventoryLoadState\.begin\(/);
  assert.match(app,/inventoryLoadState\.settle\(/);
  assert.match(app,/Promise\.allSettled\(/);
  assert.match(app,/function renderListLoadStatus\(/);
  assert.match(app,/Erneut laden/);
  assert.match(css,/\.list-load-state/);

  const start=app.indexOf('async function refreshInventories(');
  const end=app.indexOf('\nasync function refreshRenewalProgressOnly(',start);
  assert.ok(start>=0&&end>start,'real refresh lifecycle must be present');
  const fn=app.slice(start,end);
  assert.ok(fn.indexOf('inventoryLoadState.begin(')<fn.indexOf("runtimeMessage({ type: 'GET_PROFILE_STATE' })"),'loading must begin before any awaited read');
  assert.match(fn,/scopedProfileMessage\('LIST_INVENTORIES'\)/);
  assert.match(fn,/scopedProfileMessage\('LIST_TRASH'\)/);
  assert.match(fn,/inventoryLoadState\.isCurrent\(/,'stale results must be rejected');
  assert.match(fn,/Array\.isArray\(records\)/,'malformed response is not verified empty');
  assert.match(fn,/INVENTORY_LIST_LOAD_TIMING/,'one bounded startup timing diagnostic should be emitted');

  const startup=app.slice(app.indexOf('// An optional configuration'), app.indexOf('schedulePageInspect(ACCOUNT_HEALTH_FALLBACK_MS);',app.indexOf('// An optional configuration')));
  assert.ok(startup.indexOf('refreshInventories(')<startup.indexOf('refreshTrashRetentionConfiguration('),'inventory reads must start before unrelated optional retention startup');
  assert.ok(startup.indexOf('refreshInventories(')<startup.indexOf('inspectPage('),'inventory reads must not await remote page inspection');

  console.log('PASS KAR-188 independent inventory/trash pending, 61/90, confirmed empty, fail-closed error, stale profile results, startup markup/source contract');
})().catch(error=>{console.error(error);process.exitCode=1;});
