function paeth(a, b, c) {
  const p = a + b - c;
  const pa = Math.abs(p - a);
  const pb = Math.abs(p - b);
  const pc = Math.abs(p - c);
  if (pa <= pb && pa <= pc) return a;
  if (pb <= pc) return b;
  return c;
}

function readRgbaPng(file) {
  const png = fs.readFileSync(path.join(root, file));
  assert.equal(png.subarray(0, 8).toString('hex'), '89504e470d0a1a0a', `${file} PNG signature`);
  let offset = 8;
  let width = 0; let height = 0; let bitDepth = 0; let colorType = 0; let interlace = 0;
  const idat = [];
  while (offset < png.length) {
    const len = png.readUInt32BE(offset); offset += 4;
    const type = png.subarray(offset, offset + 4).toString('ascii'); offset += 4;
    const data = png.subarray(offset, offset + len); offset += len;
    offset += 4; // CRC
    if (type === 'IHDR') {
      width = data.readUInt32BE(0);
      height = data.readUInt32BE(4);
      bitDepth = data[8];
      colorType = data[9];
      interlace = data[12];
    } else if (type === 'IDAT') {
      idat.push(data);
    } else if (type === 'IEND') {
      break;
    }
  }
  assert.equal(bitDepth, 8, `${file} must be 8-bit PNG`);
  assert.equal(colorType, 6, `${file} must be RGBA PNG`);
  assert.equal(interlace, 0, `${file} must be non-interlaced PNG`);
  const raw = zlib.inflateSync(Buffer.concat(idat));
  const bpp = 4;
  const stride = width * bpp;
  const pixels = Buffer.alloc(height * stride);
  let rawOffset = 0;
  for (let y = 0; y < height; y += 1) {
    const filter = raw[rawOffset]; rawOffset += 1;
    for (let x = 0; x < stride; x += 1) {
      const value = raw[rawOffset]; rawOffset += 1;
      const left = x >= bpp ? pixels[y * stride + x - bpp] : 0;
      const up = y > 0 ? pixels[(y - 1) * stride + x] : 0;
      const upLeft = (y > 0 && x >= bpp) ? pixels[(y - 1) * stride + x - bpp] : 0;
      let decoded;
      if (filter === 0) decoded = value;
      else if (filter === 1) decoded = (value + left) & 255;
      else if (filter === 2) decoded = (value + up) & 255;
      else if (filter === 3) decoded = (value + Math.floor((left + up) / 2)) & 255;
      else if (filter === 4) decoded = (value + paeth(left, up, upLeft)) & 255;
      else assert.fail(`${file} unsupported PNG filter ${filter}`);
      pixels[y * stride + x] = decoded;
    }
  }
  return { width, height, pixels };
}

function alphaBox(file, threshold = 240) {
  const { width, height, pixels } = readRgbaPng(file);
  let minX = width; let minY = height; let maxX = -1; let maxY = -1;
  for (let y = 0; y < height; y += 1) {
    for (let x = 0; x < width; x += 1) {
      const alpha = pixels[(y * width + x) * 4 + 3];
      if (alpha >= threshold) {
        minX = Math.min(minX, x); minY = Math.min(minY, y);
        maxX = Math.max(maxX, x); maxY = Math.max(maxY, y);
      }
    }
  }
  assert.ok(maxX >= minX && maxY >= minY, `${file} has no sufficiently opaque pixels`);
  return { width, height, boxWidth: maxX - minX + 1, boxHeight: maxY - minY + 1 };
}

