const fs = require('node:fs');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const bg = fs.readFileSync('background.js','utf8');
const diagnostics = fs.readFileSync('diagnostics-service.js','utf8');
let n=0; const pass=l=>{n++;console.log('PASS '+l);};
assert.match(bg, /const DIAGNOSTIC_BATCH_FLUSH_MS = 1200;/); pass('diagnostic batch window is explicit');
assert.match(diagnostics, /let pendingEntries = \[\];/); pass('diagnostics use an in-memory pending buffer');
assert.match(diagnostics, /pendingEntries\.push\(createEntry/); pass('ordinary diagnostics enqueue instead of storage read-modify-write per event');
assert.match(bg, /function flushDiagnosticBuffer\(\)\s*\{\s*return requireDiagnosticsService\(\)\.flush\(\)/);
assert.match(diagnostics, /function flush\(\)/); pass('diagnostic buffer has an explicit flush path');
const start = diagnostics.indexOf('function requiresImmediateFlush');
const end = diagnostics.indexOf('\n      function createEntry', start);
assert.ok(start >= 0 && end > start);
const context = {}; vm.createContext(context); vm.runInContext(`${diagnostics.slice(start,end)};this.f=requiresImmediateFlush;`, context);
assert.equal(context.f('error','ANY'), true);
assert.equal(context.f('warning','ANY'), true);
assert.equal(context.f('info','RENEWAL_SOURCE_DELETE_VERIFIED'), true);
assert.equal(context.f('info','CONTENT_CONNECTION_READY'), false);
pass('critical/safety/terminal diagnostics flush immediately while routine info can batch');
console.log(`${n} PERFORMANCE-1 groups passed`);
