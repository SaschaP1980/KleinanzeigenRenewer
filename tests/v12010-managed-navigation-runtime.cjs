const assert = require('node:assert/strict');
const path = require('node:path');
const Navigation = require(path.resolve(process.cwd(), 'managed-navigation.js'));
const target = 'https://www.kleinanzeigen.de/m-meine-anzeigen.html?tab=PROJECTS';
let n = 0; const pass = label => { n += 1; console.log('PASS ' + label); };
let result = Navigation.assess({ url: 'about:blank', status: 'complete' }, target);
assert.equal(result.state, Navigation.STATES.WAITING); pass('about:blank complete is never accepted as target navigation');
result = Navigation.assess({ url: 'about:blank', pendingUrl: target, status: 'complete' }, target);
assert.equal(result.state, Navigation.STATES.WAITING); assert.equal(result.reason, 'expected-target-pending'); pass('pending target never inherits complete from previous about:blank document');
result = Navigation.assess({ url: target, status: 'loading' }, target);
assert.equal(result.state, Navigation.STATES.WAITING); assert.equal(result.matchedExpected, true); pass('expected target loading waits');
result = Navigation.assess({ url: target, status: 'complete' }, target);
assert.equal(result.state, Navigation.STATES.READY); pass('expected target complete is ready');
result = Navigation.assess({ url: 'https://kleinanzeigen.de/m-meine-anzeigen.html?tab=PROJECTS&pageNum=3', status: 'complete' }, target);
assert.equal(result.state, Navigation.STATES.READY); pass('same target with additional query parameters is accepted');
result = Navigation.assess({ url: 'chrome-error://chromewebdata/', status: 'complete' }, target);
assert.equal(result.state, Navigation.STATES.OFF_TARGET); assert.equal(result.reason, 'browser-document'); pass('browser error document is terminal off-target');
result = Navigation.assess({ url: 'https://www.kleinanzeigen.de/m-einloggen.html', status: 'complete' }, target);
assert.equal(result.state, Navigation.STATES.OFF_TARGET); assert.equal(result.reason, 'kleinanzeigen-redirect'); pass('completed Kleinanzeigen redirect is distinct from target readiness');
console.log(`${n}/7 PASS`);
