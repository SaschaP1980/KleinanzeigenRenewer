const fs = require('node:fs');
const assert = require('node:assert/strict');
const html = fs.readFileSync('app.html', 'utf8');
const css = fs.readFileSync('app.css', 'utf8');
const js = fs.readFileSync('app.js', 'utf8');
let n = 0; const pass = label => { n += 1; console.log('PASS ' + label); };
const nav = html.match(/<nav class="content-view-navigation"[\s\S]*?<\/nav>/)?.[0] || '';
assert.match(nav, /class="content-view-tabs"[\s\S]*id="inventoryViewButton"[\s\S]*id="trashViewButton"[\s\S]*id="refreshButton"/); pass('header view navigation contains separated tabs followed by refresh action');
assert.match(nav, /id="refreshButton"[^>]*class="[^"]*content-view-refresh-button[^"]*"[^>]*aria-label="Ansicht und Kontostatus aktualisieren"[^>]*title="Ansicht und Kontostatus aktualisieren"/); pass('refresh action is icon-only header control with account-aware accessible label');
const inventorySection = html.match(/<section id="inventorySection"[\s\S]*?<\/section>/)?.[0] || '';
assert.doesNotMatch(inventorySection, /id="refreshButton"/); pass('legacy inventory-title refresh button is removed');
assert.match(css, /\.content-view-navigation\s*\{[^}]*gap\s*:\s*(?:1[0-9]|[2-9][0-9])px/s); pass('refresh action is visually separated from view tabs');
assert.match(css, /\.content-view-refresh-button\s*\{[^}]*pointer-events\s*:\s*auto[^}]*border\s*:\s*1px solid #4de0b7[^}]*border-radius\s*:\s*9px 9px 0 0/s); pass('refresh action has its own cyan framed control attached to the view baseline');
const refreshStart = js.indexOf("refreshButton.addEventListener('click'");
const refreshEnd = js.indexOf('\nfunction requireDiagnosticsControlsController', refreshStart);
assert.ok(refreshStart >= 0 && refreshEnd > refreshStart);
const refresh = js.slice(refreshStart, refreshEnd);
assert.match(refresh, /await inspectPage\(\{ forceFresh: true \}\)[\s\S]*await refreshInventories\(\)/); pass('header refresh preserves the existing comprehensive refresh workflow');
console.log(`${n}/6 PASS`);
