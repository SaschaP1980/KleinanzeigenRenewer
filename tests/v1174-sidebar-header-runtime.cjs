const fs = require('node:fs');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const source = fs.readFileSync('app.js','utf8');
const start = source.indexOf('function workflowActivityModel');
const end = source.indexOf('\nfunction syncActionsActivityIndicator', start);
assert.ok(start >= 0 && end > start, 'workflowActivityModel must exist before syncActionsActivityIndicator');
const context = { console };
vm.createContext(context);
vm.runInContext(source.slice(start,end), context);
let n=0; const pass=label=>{n++;console.log('PASS '+label);};
let model = context.workflowActivityModel({ insertionLocked:true, bulkRunning:false, singleRunning:false });
assert.equal(model.running,true); pass('insertion lock marks actions as running');
model = context.workflowActivityModel({ insertionLocked:false, bulkRunning:true, singleRunning:false });
assert.equal(model.running,true); pass('bulk capture marks actions as running');
model = context.workflowActivityModel({ insertionLocked:false, bulkRunning:false, singleRunning:true });
assert.equal(model.running,true); pass('single capture marks actions as running');
model = context.workflowActivityModel({ insertionLocked:false, bulkRunning:false, singleRunning:false });
assert.equal(model.running,false); pass('idle actions do not pulse');
console.log(`${n} v1.17.4 sidebar/header runtime groups passed`);
