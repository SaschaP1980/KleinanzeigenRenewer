  function collect(documentRef = globalThis.document) {
    if (!documentRef?.querySelector) throw new Error('app-elements requires a document with querySelector().');
    const groups = {};
    const flat = {};
    for (const [groupName, selectors] of Object.entries(SELECTOR_GROUPS)) {
      const groupElements = {};
      for (const [name, selector] of Object.entries(selectors)) {
        const element = documentRef.querySelector(selector);
        groupElements[name] = element;
        flat[name] = element;
      }
      groups[groupName] = Object.freeze(groupElements);
    }
    return Object.freeze({ groups: Object.freeze(groups), flat: Object.freeze(flat) });
  }

  const api = Object.freeze({ collect });
  globalThis.KRDeps?.register?.('KRAppElements', api);
  if (typeof module !== 'undefined' && module?.exports) module.exports = api;
